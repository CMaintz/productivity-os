// Session notes built from Claude Code's own transcripts, read by the executor: no hook.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { syncSessions } from '../transcripts.mjs';
import { readFrontmatter } from '../../lib/frontmatter.mjs';

const T0 = new Date('2026-10-21T09:00:00Z');
const at = s => new Date(T0.valueOf() + s * 1000);
const ID = 'abcdef12-3456-7890-abcd-ef1234567890';

function setup() {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'tx-'));
  const vault = path.join(root, 'Vault');
  const home = path.join(root, 'home');
  const repo = path.join(root, 'Projects', 'site');
  for (const d of [path.join(vault, 'Sessions'), path.join(vault, 'Projects'), path.join(vault, '_system'), path.join(repo, '.git')]) fs.mkdirSync(d, { recursive: true });
  fs.writeFileSync(path.join(vault, 'Projects', 'site.md'), `---\ntype: project\npath: "${repo.replace(/\\/g, '/')}"\n---\n# site\n`);
  const dir = path.join(home, '.claude', 'projects', repo.replace(/[^a-zA-Z0-9]/g, '-'));
  fs.mkdirSync(dir, { recursive: true });
  return { vault, home, repo, dir };
}

const entry = (w, type, s, message, extra = {}) => ({ type, sessionId: ID, cwd: w.repo, timestamp: at(s).toISOString(), entrypoint: 'cli', isSidechain: false, uuid: `u${s}`, message, ...extra });
const prompt = (w, s, text) => entry(w, 'user', s, { role: 'user', content: text });
const reply = (w, s, text = 'Done.') => entry(w, 'assistant', s, { role: 'assistant', content: [{ type: 'text', text }] });
const toolCall = (w, s) => entry(w, 'assistant', s, { role: 'assistant', content: [{ type: 'tool_use', id: `t${s}`, name: 'Bash', input: { command: 'ls' } }] });
const toolResult = (w, s) => entry(w, 'user', s, { role: 'user', content: [{ type: 'tool_result', tool_use_id: `t${s}`, content: 'a b c' }] });
const write = (w, lines, { id = ID, append = false } = {}) => {
  const file = path.join(w.dir, `${id}.jsonl`);
  (append ? fs.appendFileSync : fs.writeFileSync)(file, lines.map(l => (typeof l === 'string' ? l : JSON.stringify(l) + '\n')).join(''));
  return file;
};
const notes = w => fs.readdirSync(path.join(w.vault, 'Sessions'));
const note = w => readFrontmatter(fs.readFileSync(path.join(w.vault, 'Sessions', notes(w)[0]), 'utf8'));
const sync = (w, s) => syncSessions(w.vault, { home: w.home, now: at(s) });

test('a transcript becomes a session note: its project, prompts and last prompt', () => {
  const w = setup();
  write(w, [prompt(w, 0, 'fix the\nbuild please'), toolCall(w, 5), toolResult(w, 6), reply(w, 10), prompt(w, 20, 'now ship it')]);
  sync(w, 30);
  assert.deepEqual(notes(w), ['2026-10-21-site-abcdef12.md']);
  const { fields, body } = note(w);
  assert.equal(fields.project, '"[[Projects/site]]"');
  assert.equal(fields.prompts, '2', 'tool results are not prompts');
  assert.equal(fields.last_prompt, '"now ship it"');
  assert.equal(fields.started, `"${at(0).toISOString()}"`);
  assert.match(body, /## Prompts\n- 09:00 fix the build please\n- 09:00 now ship it\n$/);
});

test('headless runs (claude -p, the forge workers) get no note, and sub-agent turns are not your prompts', () => {
  const w = setup();
  write(w, [{ ...prompt(w, 0, '/feature https://github.com/me/x/issues/1'), entrypoint: 'sdk-cli', sessionId: 'headless-0000' }], { id: 'headless-0000' });
  write(w, [prompt(w, 0, 'look into the bug'), { ...prompt(w, 5, 'Search the repo for X'), isSidechain: true }]);
  sync(w, 30);
  assert.deepEqual(notes(w), ['2026-10-21-site-abcdef12.md']);
  assert.equal(note(w).fields.prompts, '1');
});

test('system text and meta entries are not prompts; a slash command shows as /name', () => {
  const w = setup();
  write(w, [
    entry(w, 'user', 0, { role: 'user', content: '<command-name>/today</command-name>\n<command-message>today</command-message>\n<command-args></command-args>' }),
    entry(w, 'user', 1, { role: 'user', content: 'Caveat: the messages below were generated by the user while running local commands.' }, { isMeta: true }),
    entry(w, 'user', 2, { role: 'user', content: [{ type: 'text', text: '<system-reminder>be brief</system-reminder>' }] }),
    entry(w, 'user', 3, { role: 'user', content: [{ type: 'text', text: 'and the inbox?' }] }),
    entry(w, 'user', 4, { role: 'user', content: [{ type: 'text', text: '[Request interrupted by user for tool use]' }] }),
    entry(w, 'user', 5, { role: 'user', content: '<task-notification>\n<status>completed</status>\n</task-notification>' }),
  ]);
  sync(w, 30);
  const { fields, body } = note(w);
  assert.equal(fields.prompts, '2');
  assert.match(body, /- 09:00 \/today\n- 09:00 and the inbox\?\n$/);
});

test('only what is new is read: an appended prompt updates the note, a half-written line waits', () => {
  const w = setup();
  const file = write(w, [prompt(w, 0, 'first')]);
  sync(w, 10);
  const half = JSON.stringify(prompt(w, 20, 'second'));
  write(w, [half.slice(0, 30)], { append: true });
  sync(w, 25);
  assert.equal(note(w).fields.prompts, '1', 'the half line is not read yet');
  write(w, [half.slice(30) + '\n'], { append: true });
  sync(w, 30);
  assert.equal(note(w).fields.prompts, '2');
  assert.equal(note(w).fields.last_prompt, '"second"');
  // Rewriting the start of the file would be visible if it were read again: it isn't.
  const text = fs.readFileSync(file, 'utf8');
  fs.writeFileSync(file, text.replace('first', 'FIRST'));
  fs.utimesSync(file, at(40), at(40));
  sync(w, 41);
  assert.doesNotMatch(fs.readFileSync(path.join(w.vault, 'Sessions', notes(w)[0]), 'utf8'), /FIRST/);
});

test('status from the transcript: running, waiting on a tool, idle after the reply or a long silence', () => {
  const w = setup();
  write(w, [prompt(w, 0, 'go')]);
  sync(w, 10);
  assert.equal(note(w).fields.status, 'running');
  write(w, [toolCall(w, 20)], { append: true });
  sync(w, 30);
  assert.equal(note(w).fields.status, 'running', 'a tool call that just started is still running');
  sync(w, 120);
  assert.equal(note(w).fields.status, 'waiting', 'no result for over a minute: probably a permission prompt');
  write(w, [toolResult(w, 130)], { append: true });
  sync(w, 135);
  assert.equal(note(w).fields.status, 'running', 'the tool ran: working again');
  write(w, [reply(w, 140)], { append: true });
  sync(w, 150);
  assert.equal(note(w).fields.status, 'idle');
  write(w, [prompt(w, 200, 'one more')], { append: true });
  sync(w, 210);
  assert.equal(note(w).fields.status, 'running');
  sync(w, 200 + 31 * 60);
  assert.equal(note(w).fields.status, 'idle', 'silent for 30 minutes');
});

test('a note the old hook made for the session is reused, and new prompts go whole into the activity log', () => {
  const w = setup();
  fs.writeFileSync(path.join(w.vault, 'Sessions', '2026-10-20-site-abcdef12.md'), '---\ntype: session\nprompts: 0\n---\n# site\n');
  const long = 'x'.repeat(500);
  sync(w, -10);
  write(w, [prompt(w, 0, long)]);
  sync(w, 10);
  assert.deepEqual(notes(w), ['2026-10-20-site-abcdef12.md']);
  const lines = fs
    .readFileSync(path.join(w.vault, '_system', 'activity.jsonl'), 'utf8')
    .trim()
    .split('\n')
    .map(l => JSON.parse(l));
  assert.deepEqual(
    lines.map(l => [l.event, l.project, l.prompt]),
    [['UserPromptSubmit', 'site', long]],
  );
  sync(w, 20);
  assert.equal(
    fs
      .readFileSync(path.join(w.vault, '_system', 'activity.jsonl'), 'utf8')
      .trim()
      .split('\n').length,
    1,
    'not logged twice',
  );
});

