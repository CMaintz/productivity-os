#!/usr/bin/env node
// Builds vault-template/_system/widgets/views.md: the dashboard's widget views plus the Datacore
// adapter, bundled into one `js` code block under a "views" heading, which Obsidian's Datacore
// loads with dc.require(dc.headerLink("_system/widgets/views.md", "views")). dc.require runs the
// code as a function body and returns its result, hence the IIFE + `return`; a markdown code
// block (rather than a .js file) keeps that top-level return out of the JS linters. No imports
// remain, and Preact comes from Datacore (`dc.preact`) at runtime.
// Usage: node tools/widgets/build-views.mjs [--check]

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const VIEWS_FILE = path.join(ROOT, 'vault-template', '_system', 'widgets', 'views.md');

export async function bundleViews() {
  const out = await build({
    entryPoints: [path.join(ROOT, 'dashboard', 'src', 'widgets', 'obsidian.ts')],
    bundle: true, write: false, format: 'iife', globalName: 'productivityViews',
    platform: 'browser', target: 'es2022', legalComments: 'none', charset: 'utf8',
    footer: { js: 'return productivityViews;' },
  });
  return `# views\n\nGenerated by productivity-os (\`tools/widgets/build-views.mjs\`). Don't edit; see [[Widgets]].\n\n\`\`\`js\n${out.outputFiles[0].text}\`\`\`\n`;
}

async function main() {
  const text = await bundleViews();
  if (process.argv.includes('--check')) {
    const ok = fs.existsSync(VIEWS_FILE) && fs.readFileSync(VIEWS_FILE, 'utf8') === text;
    console.log(ok ? 'views.md is up to date' : 'views.md is stale: run node tools/widgets/build-views.mjs');
    process.exit(ok ? 0 : 1);
  }
  fs.writeFileSync(VIEWS_FILE, text);
  console.log(`wrote ${path.relative(ROOT, VIEWS_FILE)} (${text.length} bytes)`);
}

if (process.argv[1] && path.basename(process.argv[1]) === 'build-views.mjs') main();
