// Project notes in the vault, kept in step with the inventory.
// New projects get a note from scratch. Existing notes only get their `path`/`repo`
// frontmatter and the generated docs block refreshed; everything the user wrote stays.

import fs from 'node:fs';
import path from 'node:path';

const ACTIVE_DAYS = 60;
const MAX_DOCS = 30;
export const DOCS_START = '<!-- docs:start (generated by productivity-os; edits inside are overwritten) -->';
export const DOCS_END = '<!-- docs:end -->';

export const slug = s => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const yamlStr = s => JSON.stringify(s ?? '');
const fileUrl = p => encodeURI(`file:///${p.replace(/\\/g, '/').replace(/^\/+/, '')}`);

function docLink(p, d) {
  if (d.tracked && p.github) return `https://github.com/${p.github}/blob/HEAD/${encodeURI(d.path)}`;
  return fileUrl(path.join(p.path, d.path));
}

// Typed docs (ADRs, audits, decisions...) first, then plain notes; newest first within each.
const docOrder = (a, b) => (a.type === 'note') - (b.type === 'note') || b.modified.localeCompare(a.modified);

function docList(p, docs) {
  if (!docs.length) return '- none';
  const lines = [...docs].sort(docOrder).slice(0, MAX_DOCS)
    .map(d => `- ${d.type} · [${d.path}](${docLink(p, d)}) · ${d.modified.slice(0, 10)}`);
  if (docs.length > MAX_DOCS) lines.push(`- …and ${docs.length - MAX_DOCS} more`);
  return lines.join('\n');
}

/** Two lists: docs in the repo (tracked by git) and docs that only exist on this PC. */
export function docsBlock(p) {
  const docs = p.docs || [];
  const repo = docs.filter(d => d.tracked);
  const local = docs.filter(d => !d.tracked);
  return [DOCS_START, `**Repo** (${repo.length})`, docList(p, repo), '',
    `**Local only** (${local.length})`, docList(p, local), DOCS_END].join('\n');
}

export function projectNote(p, today = new Date()) {
  const last = p.lastCommitDate || p.newest;
  const ageDays = last ? (today - new Date(last)) / 864e5 : Infinity;
  return `---
type: project
status: ${ageDays <= ACTIVE_DAYS ? 'active' : 'paused'}
area:
repo: ${p.github || ''}
path: ${yamlStr(p.path)}
priority: 2
next:
updated: ${(last || today.toISOString()).slice(0, 10)}
---
# ${p.name}

## What & why
${p.languages?.length ? `Languages: ${p.languages.join(', ')}.` : ''}${p.lastCommitSubject ? ` Last commit: "${p.lastCommitSubject}".` : ''}

## Tasks

## Decisions

## Docs
${docsBlock(p)}

## Log
`;
}

/** Sets `key: value` inside the frontmatter, adding the key if it's missing. */
export function setFrontmatter(note, key, value) {
  const m = note.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!m) return note;
  const re = new RegExp(`^${key}:.*$`, 'm');
  const fm = re.test(m[1]) ? m[1].replace(re, `${key}: ${value}`) : `${m[1]}\n${key}: ${value}`;
  return note.replace(m[1], () => fm);
}

function replaceDocsBlock(note, block) {
  const start = note.indexOf(DOCS_START);
  const end = note.indexOf(DOCS_END);
  if (start >= 0 && end > start) return note.slice(0, start) + block + note.slice(end + DOCS_END.length);
  const log = note.search(/^## Log/m);
  const section = `## Docs\n${block}\n\n`;
  return log >= 0 ? note.slice(0, log) + section + note.slice(log) : `${note.trimEnd()}\n\n${section}`;
}

export function refreshNote(note, p) {
  let out = setFrontmatter(note, 'path', yamlStr(p.path));
  if (p.github) out = setFrontmatter(out, 'repo', p.github);
  return replaceDocsBlock(out, docsBlock(p));
}

/** Existing project notes, indexed by their `repo` frontmatter and by file slug. */
function indexNotes(dir) {
  const byRepo = new Map(); const bySlug = new Map();
  for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.md'))) {
    const file = path.join(dir, f);
    const repo = fs.readFileSync(file, 'utf8').match(/^repo:\s*(\S+)\s*$/m)?.[1];
    if (repo) byRepo.set(repo.toLowerCase(), file);
    bySlug.set(path.basename(f, '.md'), file);
  }
  return { byRepo, bySlug };
}

export function syncProjects(vault, inventory, today = new Date()) {
  const dir = path.join(vault, 'Projects'); fs.mkdirSync(dir, { recursive: true });
  const notes = indexNotes(dir);
  const result = { created: [], refreshed: [], unchanged: [] };
  for (const p of inventory.projects || []) {
    const existing = (p.github && notes.byRepo.get(p.github.toLowerCase())) || notes.bySlug.get(slug(p.name));
    if (!existing) {
      const file = path.join(dir, `${slug(p.name)}.md`);
      fs.writeFileSync(file, projectNote(p, today)); result.created.push(file); continue;
    }
    const before = fs.readFileSync(existing, 'utf8'); const after = refreshNote(before, p);
    if (after === before) { result.unchanged.push(existing); continue; }
    fs.writeFileSync(existing, after); result.refreshed.push(existing);
  }
  return result;
}
