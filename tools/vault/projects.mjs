// Project notes in the vault, kept in step with the inventory.
// New projects get a note from scratch. Existing notes only get their `path`/`repo`
// frontmatter and the generated docs block refreshed; everything the user wrote stays.

import fs from 'node:fs';
import path from 'node:path';
import { fieldsOf, setFrontmatter } from '../lib/frontmatter.mjs';
import { samePath } from '../lib/paths.mjs';
import { writeFileAtomic } from '../lib/atomic-write.mjs';

const ACTIVE_DAYS = 60;
const MAX_DOCS = 30;
export const DOCS_START = '<!-- docs:start (generated by productivity-os; edits inside are overwritten) -->';
export const DOCS_END = '<!-- docs:end -->';

export const slug = s =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
const yamlStr = s => JSON.stringify(s ?? '');
const fileUrl = p => encodeURI(`file:///${p.replace(/\\/g, '/').replace(/^\/+/, '')}`);

function docLink(p, d) {
  if (d.tracked && p.github) return `https://github.com/${p.github}/blob/HEAD/${encodeURI(d.path)}`;
  return fileUrl(path.join(p.path, d.path));
}

// Typed docs (ADRs, audits, decisions...) first, then plain notes; newest first within each.
const docOrder = (a, b) => (a.type === 'note') - (b.type === 'note') || b.modified.localeCompare(a.modified);

function docList(p, docs) {
  if (!docs.length) return '- none';
  const lines = [...docs]
    .sort(docOrder)
    .slice(0, MAX_DOCS)
    .map(d => `- ${d.type} · [${d.path}](${docLink(p, d)}) · ${d.modified.slice(0, 10)}`);
  if (docs.length > MAX_DOCS) lines.push(`- …and ${docs.length - MAX_DOCS} more`);
  return lines.join('\n');
}

/** Two lists: docs in the repo (tracked by git) and docs that only exist on this PC. */
export function docsBlock(p) {
  const docs = p.docs || [];
  const repo = docs.filter(d => d.tracked);
  const local = docs.filter(d => !d.tracked);
  return [DOCS_START, `**Repo** (${repo.length})`, docList(p, repo), '', `**Local only** (${local.length})`, docList(p, local), DOCS_END].join('\n');
}

export function projectNote(p, today = new Date()) {
  const last = p.lastCommitDate || p.newest;
  const ageDays = last ? (today - new Date(last)) / 864e5 : Infinity;
  return `---
type: project
status: ${ageDays <= ACTIVE_DAYS ? 'active' : 'paused'}
area:
repo: ${p.github || ''}
path: ${yamlStr(p.path)}
priority: 2
next:
updated: ${(last || today.toISOString()).slice(0, 10)}
---
# ${p.name}

## What & why
${p.languages?.length ? `Languages: ${p.languages.join(', ')}.` : ''}${p.lastCommitSubject ? ` Last commit: "${p.lastCommitSubject}".` : ''}

## Tasks

## Decisions

## Docs
${docsBlock(p)}

## Log
`;
}

/**
 * Swaps a generated block (between its start and end markers) for a new one. When the note
 * has no such block yet, adds it as `## <heading>` before the first `## <before>` section.
 */
export function replaceBlock(note, { start: startMark, end: endMark, heading, before = 'Log' }, block) {
  const start = note.indexOf(startMark);
  const end = note.indexOf(endMark);
  if (start >= 0 && end > start) return note.slice(0, start) + block + note.slice(end + endMark.length);
  const at = note.search(new RegExp(`^## ${before}\\b`, 'm'));
  const section = `## ${heading}\n${block}\n\n`;
  return at >= 0 ? note.slice(0, at) + section + note.slice(at) : `${note.trimEnd()}\n\n${section}`;
}

const DOCS = { start: DOCS_START, end: DOCS_END, heading: 'Docs' };

export function refreshNote(note, p) {
  let out = setFrontmatter(note, 'path', yamlStr(p.path));
  if (p.github) out = setFrontmatter(out, 'repo', p.github);
  return replaceBlock(out, DOCS, docsBlock(p));
}

function readNotes(dir) {
  return fs
    .readdirSync(dir)
    .filter(f => f.endsWith('.md'))
    .map(f => {
      const file = path.join(dir, f);
      const { path: notePath, repo } = fieldsOf(fs.readFileSync(file, 'utf8'));
      return { file, slug: path.basename(f, '.md'), repo: repo ? String(repo).toLowerCase() : null, path: notePath ? String(notePath) : null };
    });
}

/**
 * Pairs each project with its note in three passes over all projects: exact path, then
 * repo, then name. Path wins, so two checkouts of one repo keep separate notes. Repo and
 * name only pick up notes no project matched by path, which is how a moved or renamed
 * folder finds its old note; a name match never takes a note about a different repo.
 */
function matchNotes(projects, notes) {
  const claimed = new Set();
  const match = new Map();
  const pass = test => {
    for (const p of projects) {
      if (match.has(p)) continue;
      const n = notes.find(n => !claimed.has(n) && test(n, p));
      if (n) {
        claimed.add(n);
        match.set(p, n);
      }
    }
  };
  pass((n, p) => samePath(n.path, p.path));
  pass((n, p) => !!p.github && n.repo === p.github.toLowerCase());
  pass((n, p) => n.slug === slug(p.name) && (!n.repo || n.repo === p.github?.toLowerCase()));
  return match;
}

/** The note for the checkout at `dir`, matched by its `path` frontmatter. */
export function noteForPath(vault, dir) {
  const notesDir = path.join(vault, 'Projects');
  if (!fs.existsSync(notesDir)) return null;
  return readNotes(notesDir).find(n => samePath(n.path, dir))?.file ?? null;
}

// A name already taken by another checkout's note gets the parent folder as a prefix.
function newNoteFile(dir, p) {
  const base = slug(p.name);
  if (!fs.existsSync(path.join(dir, `${base}.md`))) return path.join(dir, `${base}.md`);
  const prefixed = `${slug(path.basename(path.dirname(p.path)))}-${base}`;
  for (let i = 1; ; i++) {
    const file = path.join(dir, `${prefixed}${i > 1 ? `-${i}` : ''}.md`);
    if (!fs.existsSync(file)) return file;
  }
}

export function syncProjects(vault, inventory, today = new Date()) {
  const dir = path.join(vault, 'Projects');
  fs.mkdirSync(dir, { recursive: true });
  // Worktrees are branches of a checkout that already has a note.
  const projects = (inventory.projects || []).filter(p => !p.worktree);
  const match = matchNotes(projects, readNotes(dir));
  const result = { created: [], refreshed: [], unchanged: [] };
  for (const p of projects) {
    const existing = match.get(p)?.file;
    if (!existing) {
      const file = newNoteFile(dir, p);
      fs.writeFileSync(file, projectNote(p, today));
      result.created.push(file);
      continue;
    }
    const before = fs.readFileSync(existing, 'utf8');
    const after = refreshNote(before, p);
    if (after === before) {
      result.unchanged.push(existing);
      continue;
    }
    writeFileAtomic(existing, after);
    result.refreshed.push(existing);
  }
  return result;
}

/**
 * The project a cwd belongs to: the nearest folder with a .git, else the cwd itself, and a
 * worktree's main checkout. Its note is the one whose `path` is that folder; notes without
 * a path are found by name.
 */
export function projectFor(cwd, vaultDir) {
  let dir = path.resolve(cwd || '.');
  for (let d = dir; ; d = path.dirname(d)) {
    if (fs.existsSync(path.join(d, '.git'))) {
      dir = d;
      break;
    }
    if (path.dirname(d) === d) break;
  }
  dir = mainCheckout(dir);
  const file = noteForPath(vaultDir, dir);
  if (file) return { slug: path.basename(file, '.md'), note: `Projects/${path.basename(file, '.md')}` };
  const s = slug(path.basename(dir)) || 'unknown';
  const note = fs.existsSync(path.join(vaultDir, 'Projects', `${s}.md`)) ? `Projects/${s}` : null;
  return { slug: s, note };
}

// A worktree's .git is a file pointing at <main>/.git/worktrees/<name>.
function mainCheckout(dir) {
  let gitDir;
  try {
    gitDir = fs.readFileSync(path.join(dir, '.git'), 'utf8').match(/^gitdir:\s*(.+?)\s*$/m)?.[1];
  } catch {
    return dir;
  }
  if (!gitDir) return dir;
  const wt = path.resolve(dir, gitDir);
  return path.basename(path.dirname(wt)) === 'worktrees' ? path.dirname(path.dirname(path.dirname(wt))) : dir;
}
