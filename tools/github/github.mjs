// Pure helpers for the GitHub block in project notes: the GraphQL query, a summary of
// one repo's state, and the markdown + frontmatter written from it. sync.mjs does the I/O.

export const GH_START = '<!-- github:start (generated by productivity-os; edits inside are overwritten) -->';
export const GH_END = '<!-- github:end -->';
export const GH_BLOCK = { start: GH_START, end: GH_END, heading: 'GitHub', before: 'Docs' };

const AGENT_LABELS = ['agent:ready', 'agent:working', 'agent:blocked'];
const MAX_ISSUES = 10;

export const REPO_QUERY = `query($owner: String!, $name: String!) {
  repository(owner: $owner, name: $name) {
    url isArchived
    defaultBranchRef { name target { ... on Commit { statusCheckRollup { state } } } }
    pullRequests(states: OPEN, first: 30, orderBy: {field: UPDATED_AT, direction: DESC}) {
      totalCount
      nodes { number title url isDraft reviewDecision updatedAt
        commits(last: 1) { nodes { commit { statusCheckRollup { state } } } } }
    }
    issues(states: OPEN, first: 50, orderBy: {field: UPDATED_AT, direction: DESC}) {
      totalCount
      nodes { number title url labels(first: 10) { nodes { name } } }
    }
  }
}`;

/** GitHub's rollup states, folded into four words that read well in a table. */
export function ciWord(state) {
  if (!state) return 'none';
  if (state === 'SUCCESS') return 'passing';
  if (state === 'FAILURE' || state === 'ERROR') return 'failing';
  return 'pending';
}

const ICON = { passing: '✅', failing: '❌', pending: '⏳', none: '·' };
const REVIEW = { APPROVED: 'approved', CHANGES_REQUESTED: 'changes requested', REVIEW_REQUIRED: 'needs review' };

const labelsOf = issue => issue.labels.nodes.map(l => l.name);

function summarisePr(pr) {
  const state = pr.commits.nodes[0]?.commit.statusCheckRollup?.state;
  return { number: pr.number, title: pr.title, url: pr.url, draft: pr.isDraft, ci: ciWord(state), review: REVIEW[pr.reviewDecision] ?? null };
}

/** Everything the note needs from one repository's GraphQL result. */
export function summarise(repo) {
  const issues = repo.issues.nodes.map(i => ({ number: i.number, title: i.title, url: i.url, labels: labelsOf(i) }));
  const agent = Object.fromEntries(AGENT_LABELS.map(l => [l.split(':')[1], issues.filter(i => i.labels.includes(l))]));
  return {
    url: repo.url,
    archived: repo.isArchived,
    branch: repo.defaultBranchRef?.name ?? 'main',
    ci: ciWord(repo.defaultBranchRef?.target?.statusCheckRollup?.state),
    prs: repo.pullRequests.nodes.map(summarisePr),
    prCount: repo.pullRequests.totalCount,
    issueCount: repo.issues.totalCount,
    agent,
    otherIssues: issues.filter(i => !i.labels.some(l => AGENT_LABELS.includes(l))),
  };
}

function prLine(pr) {
  const bits = [`CI ${ICON[pr.ci]}`, pr.review, pr.draft ? 'draft' : null].filter(Boolean).join(' · ');
  return `- [#${pr.number}](${pr.url}) ${pr.title} · ${bits}`;
}

function agentLines(agent) {
  const counts = `ready ${agent.ready.length} · working ${agent.working.length} · blocked ${agent.blocked.length}`;
  const blocked = agent.blocked.map(i => `- ⛔ [#${i.number}](${i.url}) ${i.title}`);
  return [`**Agent tickets:** ${counts}`, ...blocked];
}

/** The markdown block between the github markers. */
export function githubBlock(s, syncedAt) {
  const issues = s.otherIssues.slice(0, MAX_ISSUES).map(i => `- [#${i.number}](${i.url}) ${i.title}`);
  return [
    GH_START,
    `**${s.branch}:** ${ICON[s.ci]} ${s.ci}${s.archived ? ' · archived' : ''} · [repo](${s.url}) · synced ${syncedAt.slice(0, 16).replace('T', ' ')}`,
    '',
    `**Open PRs** (${s.prCount})`,
    ...(s.prs.length ? s.prs.map(prLine) : ['- none']),
    '',
    ...agentLines(s.agent),
    '',
    `**Open issues** (${s.issueCount})`,
    ...(issues.length ? issues : ['- none']),
    ...(s.otherIssues.length > MAX_ISSUES ? [`- …and ${s.otherIssues.length - MAX_ISSUES} more`] : []),
    GH_END,
  ].join('\n');
}

/** Frontmatter fields Bases and the skills can filter on. */
export function githubFields(s, syncedAt) {
  return {
    ci: s.ci,
    open_prs: s.prCount,
    failing_prs: s.prs.filter(p => p.ci === 'failing').length,
    agent_blocked: s.agent.blocked.length,
    github_synced: syncedAt.slice(0, 10),
  };
}
